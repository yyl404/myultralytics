#!/usr/bin/env python3
"""
Generate replay dataset from prototypes generated by generate_prototypes.py.

This script:
1. Loads prototypes file (.pt) containing prototypes and meta_info
2. Extracts image paths and corresponding labels from meta_info
3. Copies images and creates label files to form a new dataset
4. Dataset format follows YOLO format (same as VOC)

Usage:
    python tools/generate_replay_dataset.py \
        --prototypes <path_to_prototypes.pt> \
        --output <path_to_output_dataset> \
        [--copy_images] \
        [--use_all_annotations]

Arguments:
    --prototypes: Path to prototypes file (.pt) generated by generate_prototypes.py [required]
    --output: Path to output dataset directory [required]
    --copy_images: Whether to copy images to output directory (default: False, creates symlinks)
    --use_all_annotations: Whether to use all annotations from original label file or only prototype bbox (default: True)
"""

import argparse
import os
import shutil
from pathlib import Path
from collections import defaultdict
import torch
from tqdm import tqdm

from ultralytics.utils import LOGGER, YAML
from ultralytics.utils.metrics import bbox_iou


def find_matching_bbox(bbox_norm, label_lines, iou_threshold=0.8):
    """
    Find matching bbox in label file by IOU.
    
    Args:
        bbox_norm: Normalized bbox [x_center, y_center, width, height]
        label_lines: List of label lines, each is [class_id, x, y, w, h]
        iou_threshold: IOU threshold for matching
    
    Returns:
        Matching label line index, or None if no match
    """
    if not label_lines:
        return None
    
    if isinstance(bbox_norm, torch.Tensor):
        bbox_norm = bbox_norm.tolist()
    
    bbox_tensor = torch.tensor([bbox_norm], dtype=torch.float32)
    
    best_iou = 0.0
    best_idx = None
    
    for idx, line in enumerate(label_lines):
        if len(line) < 5:
            continue
        try:
            label_bbox = torch.tensor([[float(line[1]), float(line[2]), float(line[3]), float(line[4])]], 
                                      dtype=torch.float32)
            iou = bbox_iou(bbox_tensor, label_bbox, xywh=True)
            iou_val = iou.item()
            if iou_val >= iou_threshold and iou_val > best_iou:
                best_iou = iou_val
                best_idx = idx
        except (ValueError, IndexError):
            continue
    
    return best_idx


def load_original_labels(img_path, label_dir):
    """
    Load original label file for an image.
    
    Args:
        img_path: Path to image file
        label_dir: Directory containing label files
    
    Returns:
        List of label lines, each is [class_id, x, y, w, h]
    """
    img_name = Path(img_path).stem
    label_path = os.path.join(label_dir, img_name + '.txt')
    
    if not os.path.exists(label_path):
        return []
    
    with open(label_path, 'r') as f:
        lines = [line.strip().split() for line in f.readlines() if line.strip()]
    
    return lines


def find_dataset_yaml(img_path):
    """
    Find the original dataset.yaml file for an image by searching parent directories.
    
    Args:
        img_path: Path to image file
    
    Returns:
        Path to dataset.yaml file, or None if not found
    """
    # Start from image directory and search up
    current = Path(img_path).parent
    
    # Search up to 5 levels
    for _ in range(5):
        yaml_path = current / 'dataset.yaml'
        if yaml_path.exists():
            return str(yaml_path)
        
        # Also check if current directory name suggests it's a dataset root
        # (e.g., contains 'images' or 'labels' subdirectories)
        if (current / 'images').exists() or (current / 'labels').exists():
            yaml_path = current / 'dataset.yaml'
            if yaml_path.exists():
                return str(yaml_path)
        
        current = current.parent
        if current == current.parent:  # Reached root
            break
    
    return None


def load_class_names_from_yaml(yaml_path):
    """
    Load class names from a dataset.yaml file.
    
    Args:
        yaml_path: Path to dataset.yaml file
    
    Returns:
        Dictionary mapping class_id to class_name, or None if failed
    """
    try:
        data_cfg = YAML.load(yaml_path)
        names = data_cfg.get('names', {})
        # Convert to int keys if they are strings
        if names and isinstance(list(names.keys())[0], str):
            names = {int(k): v for k, v in names.items()}
        return names
    except Exception as e:
        LOGGER.warning(f"Failed to load class names from {yaml_path}: {e}")
        return None


def generate_replay_dataset(args):
    """
    Generate replay dataset from prototypes.
    """
    # 1. Load prototypes
    LOGGER.info(f"Loading prototypes from {args.prototypes}...")
    data = torch.load(args.prototypes, map_location='cpu')
    
    prototypes_pos = data.get('prototypes', [])
    meta_info_pos = data.get('meta_info', [])
    prototypes_neg = data.get('prototypes_neg', [])
    meta_info_neg = data.get('meta_info_neg', [])
    
    # 2. Collect unique images and their annotations
    # Structure: img_path -> list of (class_id, bbox_norm, original_label_path)
    image_annotations = defaultdict(list)
    image_meta = {}  # Store additional metadata like original label directory
    
    # Process positive prototypes
    for layer_idx, (protos, metas) in enumerate(zip(prototypes_pos, meta_info_pos)):
        if protos is None or not metas:
            continue
        
        for meta in metas:
            img_path = meta['img_path']
            if not os.path.exists(img_path):
                LOGGER.warning(f"Image {img_path} not found, skipped")
                continue
            
            # Store metadata for later use
            if img_path not in image_meta:
                image_meta[img_path] = {
                    'dataset': meta.get('dataset', 'unknown'),
                    'HWs': meta.get('HWs', [])
                }
            
            # Get bbox_gt_norm (normalized bbox in YOLO format)
            if 'bbox_gt_norm' in meta:
                bbox_norm = meta['bbox_gt_norm']
                if isinstance(bbox_norm, torch.Tensor):
                    bbox_norm = bbox_norm.tolist()
                
                # We need to find the original class_id from the original label file
                # For now, we'll store the bbox and find the class_id later
                image_annotations[img_path].append({
                    'bbox_norm': bbox_norm,
                    'layer_idx': layer_idx,
                    'type': 'pos'
                })
    
    # Process negative prototypes (optional, usually we don't need labels for negative samples)
    if args.include_negative:
        for layer_idx, (protos, metas) in enumerate(zip(prototypes_neg, meta_info_neg)):
            if protos is None or not metas:
                continue
            
            for meta in metas:
                img_path = meta['img_path']
                if not os.path.exists(img_path):
                    continue
                
                if img_path not in image_meta:
                    image_meta[img_path] = {
                        'dataset': meta.get('dataset', 'unknown'),
                        'HWs': meta.get('HWs', [])
                    }
                
                # Negative samples don't have bbox_gt_norm, so we'll use empty labels
                image_annotations[img_path].append({
                    'bbox_norm': None,
                    'layer_idx': layer_idx,
                    'type': 'neg'
                })
    
    LOGGER.info(f"Found {len(image_annotations)} unique images")
    
    # 3. Find original label files and extract class_ids
    # Build a mapping of image paths to their label directories
    img_to_label_dir = {}
    label_dirs_found = set()
    
    for img_path in image_annotations.keys():
        # Try common label directory patterns
        img_dir = os.path.dirname(img_path)
        possible_label_dirs = [
            img_dir.replace('images', 'labels'),
            os.path.join(os.path.dirname(img_dir), 'labels'),
            os.path.join(os.path.dirname(os.path.dirname(img_dir)), 'labels', os.path.basename(img_dir))
        ]
        
        label_dir = None
        for possible_dir in possible_label_dirs:
            if os.path.exists(possible_dir):
                label_dir = possible_dir
                break
        
        if label_dir is None:
            # Try to find label directory by searching parent directories
            parent = Path(img_path).parent
            for _ in range(3):  # Search up to 3 levels
                possible = parent / 'labels'
                if possible.exists():
                    label_dir = str(possible)
                    break
                parent = parent.parent
        
        if label_dir:
            img_to_label_dir[img_path] = label_dir
            if label_dir not in label_dirs_found:
                label_dirs_found.add(label_dir)
                LOGGER.info(f"Found label directory: {label_dir}")
        else:
            LOGGER.warning(f"Could not find label directory for {img_path}")
    
    # 4. Match bboxes with original labels to get class_ids
    final_annotations = defaultdict(list)  # img_path -> list of (class_id, bbox_norm)
    
    for img_path, annotations in tqdm(image_annotations.items(), desc="Matching annotations"):
        # Get label directory from mapping
        label_dir = img_to_label_dir.get(img_path)
        if label_dir is None:
            LOGGER.warning(f"Could not find label directory for {img_path}, skipping")
            continue
        
        # Load original labels
        original_labels = load_original_labels(img_path, label_dir)
        
        if args.use_all_annotations:
            # Use all annotations from original label file
            for label_line in original_labels:
                if len(label_line) >= 5:
                    try:
                        class_id = int(label_line[0])
                        bbox_norm = [float(label_line[1]), float(label_line[2]), 
                                   float(label_line[3]), float(label_line[4])]
                        final_annotations[img_path].append((class_id, bbox_norm))
                    except (ValueError, IndexError):
                        LOGGER.warning(f"Invalid label line in {img_path}: {label_line}")
                        continue
        else:
            # Only use annotations that match prototype bboxes
            matched_indices = set()
            for ann in annotations:
                if ann['bbox_norm'] is None:
                    # Negative sample, skip (or use empty label)
                    continue
                
                # Find matching bbox in original labels
                match_idx = find_matching_bbox(ann['bbox_norm'], original_labels)
                if match_idx is not None and match_idx not in matched_indices:
                    label_line = original_labels[match_idx]
                    try:
                        class_id = int(label_line[0])
                        bbox_norm = ann['bbox_norm']
                        final_annotations[img_path].append((class_id, bbox_norm))
                        matched_indices.add(match_idx)
                    except (ValueError, IndexError):
                        LOGGER.warning(f"Invalid label line in {img_path}: {label_line}")
                        continue
                elif match_idx is None:
                    # If no match found, we can't determine class_id, skip
                    LOGGER.debug(f"Could not find matching bbox for {img_path}, skipping annotation")
    
    LOGGER.info(f"Final dataset contains {len(final_annotations)} images")
    
    # 5. Create output directory structure
    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)
    
    images_dir = output_dir / 'images'
    labels_dir = output_dir / 'labels'
    images_dir.mkdir(exist_ok=True)
    labels_dir.mkdir(exist_ok=True)
    
    # 6. Copy/symlink images and create label files
    LOGGER.info(f"Creating dataset in {output_dir}...")
    for img_path, annotations in tqdm(final_annotations.items(), desc="Creating dataset"):
        if not annotations:
            continue
        
        img_name = Path(img_path).name
        output_img_path = images_dir / img_name
        output_label_path = labels_dir / (Path(img_name).stem + '.txt')
        
        # Copy or symlink image
        if args.copy_images:
            shutil.copy2(img_path, output_img_path)
        else:
            # Create symlink (relative path)
            try:
                if output_img_path.exists() or output_img_path.is_symlink():
                    output_img_path.unlink()
                rel_path = os.path.relpath(img_path, output_img_path.parent)
                output_img_path.symlink_to(rel_path)
            except Exception as e:
                LOGGER.warning(f"Failed to create symlink for {img_path}: {e}, copying instead")
                shutil.copy2(img_path, output_img_path)
        
        # Create label file
        with open(output_label_path, 'w') as f:
            for class_id, bbox_norm in annotations:
                line = f"{class_id} {bbox_norm[0]:.6f} {bbox_norm[1]:.6f} {bbox_norm[2]:.6f} {bbox_norm[3]:.6f}\n"
                f.write(line)
    
    # 7. Create dataset.yaml file
    # Collect all class IDs used in the dataset
    all_class_ids = set()
    for annotations in final_annotations.values():
        for class_id, _ in annotations:
            all_class_ids.add(class_id)
    
    if not all_class_ids:
        LOGGER.warning("No annotations found, creating empty dataset.yaml")
        max_class_id = -1
    else:
        max_class_id = max(all_class_ids)
    
    # 7.1. Collect class names from original dataset yaml files
    LOGGER.info("Collecting class names from original dataset yaml files...")
    class_names_map = {}  # class_id -> class_name
    dataset_yamls_found = set()
    
    for img_path in final_annotations.keys():
        # Find original dataset yaml file
        dataset_yaml_path = find_dataset_yaml(img_path)
        if dataset_yaml_path and dataset_yaml_path not in dataset_yamls_found:
            dataset_yamls_found.add(dataset_yaml_path)
            names = load_class_names_from_yaml(dataset_yaml_path)
            if names:
                # Merge class names, prefer existing mappings if conflict
                for class_id, class_name in names.items():
                    if class_id not in class_names_map:
                        class_names_map[class_id] = class_name
                    elif class_names_map[class_id] != class_name:
                        LOGGER.warning(f"Class ID {class_id} has conflicting names: "
                                     f"'{class_names_map[class_id]}' vs '{class_name}'. "
                                     f"Using '{class_names_map[class_id]}'")
    
    # Fill in missing class names with placeholders
    for class_id in range(max_class_id + 1):
        if class_id not in class_names_map:
            class_names_map[class_id] = f"class_{class_id}"
            LOGGER.warning(f"Class ID {class_id} not found in original datasets, using placeholder 'class_{class_id}'")
    
    # 7.2. Generate yaml content
    yaml_content = f"""# Replay dataset generated from prototypes
# Source: {args.prototypes}
# Total images: {len(final_annotations)}

train: images
val: images
test: images

names:
"""
    # Write class names in order
    for class_id in sorted(class_names_map.keys()):
        yaml_content += f"  {class_id}: {class_names_map[class_id]}\n"
    
    yaml_path = output_dir / 'dataset.yaml'
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)
    
    if dataset_yamls_found:
        LOGGER.info(f"Loaded class names from {len(dataset_yamls_found)} original dataset yaml file(s)")
    
    # 8. Print summary
    total_annotations = sum(len(anns) for anns in final_annotations.values())
    LOGGER.info(f"Dataset created successfully at {output_dir}")
    LOGGER.info(f"Total images: {len(final_annotations)}")
    LOGGER.info(f"Total annotations: {total_annotations}")
    LOGGER.info(f"Class IDs used: {sorted(all_class_ids)}")
    LOGGER.info(f"Dataset YAML: {yaml_path}")
    if dataset_yamls_found:
        LOGGER.info(f"Class names loaded from original dataset yaml files")
    else:
        LOGGER.warning(f"No original dataset yaml files found, using placeholder class names")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate replay dataset from prototypes")
    parser.add_argument("--prototypes", required=True, help="Path to prototypes file (.pt)")
    parser.add_argument("--output", required=True, help="Path to output dataset directory")
    parser.add_argument("--copy_images", action="store_true", 
                       help="Copy images instead of creating symlinks (default: False)")
    parser.add_argument("--use_all_annotations", action="store_true", default=True,
                       help="Use all annotations from original label file (default: True)")
    parser.add_argument("--include_negative", action="store_true",
                       help="Include negative prototypes (default: False)")
    args = parser.parse_args()
    
    generate_replay_dataset(args)

